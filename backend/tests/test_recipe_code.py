"""The code shown for a step must do exactly what the engine does — otherwise the code view lies."""

import numpy as np
import pandas as pd
import pytest

from app.recipe import Context, Line, apply_to, replay, STEP_TYPES
from app.recipe_code import BUILDERS, step_code

TARGET = "label"
TRAIN = pd.DataFrame({
    "age": [20.0, None, 40.0, 35.0, None, 50.0],
    "income": ["$1,000", "$2,500", None, "$4,000", "$5,500", "$6,000"],
    "city": ["London", "Paris", None, "London", "Berlin", "Paris"],
    "name": ["  Ann ", "BOB", "cy", None, "Di", "ed "],
    "size": [1.0, 2.0, 3.0, 2.0, 1.0, 9.0],
    "label": [0, 1, 0, 1, 0, 1],
})
TEST = pd.DataFrame({
    "age": [None, 60.0],
    "income": ["$9,000", None],
    "city": ["Madrid", "Paris"],  # Madrid never seen in training
    "name": ["Zed", None],
    "size": [4.0, None],
    "label": [1, 0],
})

STEPS = [
    ("remove_columns", {"columns": ["name"]}),
    ("clean_numeric_string", {"column": "income"}),
    ("standardize_text", {"column": "name"}),
    ("log_transform", {"column": "size"}),
    ("remove_duplicates", {}),
    ("impute_missing", {"column": "age", "strategy": "median"}),
    ("impute_missing", {"column": "city", "strategy": "mode"}),
    ("impute_all_missing", {}),
    ("impute_all_missing", {"strategy": "median"}),
    ("encode_categorical", {"column": "city", "method": "label"}),
    ("encode_categorical", {"column": "city", "method": "onehot"}),
    ("encode_all_categorical", {"method": "onehot"}),
    ("scale_features", {"columns": ["age", "size"]}),
    ("scale_all_features", {}),
]


def run_shown_code(code: str, train: pd.DataFrame, test: pd.DataFrame):
    scope = {}
    exec(code, scope)  # trusted: code generated by our own builders
    learned = scope["learn"](train.copy())
    return learned, scope["apply"](train.copy(), learned), scope["apply"](test.copy(), learned)


def test_every_step_has_a_code_view():
    assert set(BUILDERS) == set(STEP_TYPES)


@pytest.mark.parametrize("tool,args", STEPS, ids=[f"{t}-{a}" for t, a in STEPS])
def test_shown_code_matches_engine(tool, args):
    ctx = Context(target=TARGET)
    # Numeric-only steps need a numeric frame to start from (as they would after cleaning)
    train, test = TRAIN.copy(), TEST.copy()
    if tool.startswith("scale") or tool == "log_transform":
        train, test = train[["age", "size", "label"]].fillna(1.0), test[["age", "size", "label"]].fillna(1.0)

    line = Line(tool, args)
    engine_train = replay(train, [line], ctx)
    engine_test = apply_to(test, [line], ctx)

    learned, shown_train, shown_test = run_shown_code(step_code(line, TARGET), train, test)

    pd.testing.assert_frame_equal(shown_train, engine_train, check_dtype=False, atol=1e-5)
    if STEP_TYPES[tool].kind != "train_only":
        pd.testing.assert_frame_equal(shown_test.reset_index(drop=True), engine_test.reset_index(drop=True),
                                      check_dtype=False, atol=1e-5)


def test_code_ends_with_the_learned_values():
    line = Line("impute_missing", {"column": "age", "strategy": "median"})
    replay(TRAIN, [line], Context(target=TARGET))
    code = step_code(line, TARGET)
    assert "train['age'].median()" in code
    assert '#     "age": 37.5' in code
